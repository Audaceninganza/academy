/* ══════════════════════════════════════════════
   LANGUAGE SWITCHER
══════════════════════════════════════════════ */
let lang = "en";
function setLang(l, btn) {
  lang = l;
  document
    .querySelectorAll(".lang-btn")
    .forEach((b) => b.classList.remove("active"));
  btn.classList.add("active");
  document.querySelectorAll("[data-t]").forEach((el) => {
    const k = el.getAttribute("data-t");
    if (T[l][k] !== undefined) el.innerHTML = T[l][k];
  });
  const activeBtn = document.querySelector(".tab-btn.active");
  if (activeBtn) {
    const type = activeBtn.id === "tabProgramming" ? "programming" : "english";
    showCourses(type, activeBtn, true);
  }
}

/* ══════════════════════════════════════════════
   COURSES
 ══════════════════════════════════════════════ */
function card(icon, cls, titleKey, descKey) {
  const t = T[lang];
  return `<div class="course-card">
    <div class="cc-icon ${cls}">${icon}</div>
    <h3>${t[titleKey] || ""}</h3>
    <p>${t[descKey] || ""}</p>
  </div>`;
}

function showCourses(type, btn, instant) {
  document
    .querySelectorAll(".tab-btn")
    .forEach((b) => b.classList.remove("active"));
  if (btn) btn.classList.add("active");
  const el = document.getElementById("course-content");
  if (!instant) {
    el.style.opacity = "0";
    el.style.transform = "translateY(8px)";
  }

  const engCards = [
    card("📝", "cc-amber", "c_rw_t", "c_rw_d"),
    card("🗣️", "cc-amber", "c_sl_t", "c_sl_d"),
    card("📚", "cc-amber", "c_gr_t", "c_gr_d"),
  ];
  const progCards = [
    card("🐍", "cc-purple", "c_first_t", "c_first_d"),
    card("🌐", "cc-teal", "c_second_t", "c_second_d"),
    card("🔧", "cc-teal", "c_third_t", "c_third_d"),
  ];

  const html = type === "programming" ? progCards.join("") : engCards.join("");

  setTimeout(
    () => {
      el.innerHTML = `<div class="course-grid">${html}</div>`;
      if (!instant) {
        el.style.transition = "opacity .3s, transform .3s";
        el.style.opacity = "1";
        el.style.transform = "translateY(0)";
      }
    },
    instant ? 0 : 160,
  );
}

/* ══════════════════════════════════════════════
   FORM
══════════════════════════════════════════════ */
document
  .getElementById("reg-form")
  .addEventListener("submit", async function (e) {
    e.preventDefault();
    const form = e.target;
    const result = document.getElementById("form-result");
    const btn = document.getElementById("fBtn");
    const txtEl = document.getElementById("fBtnText");
    const t = T[lang];

    const name = form.name.value.trim();
    const age = parseInt(form.age.value, 10);
    const phone = form.phone.value.trim();
    const course = form.course.value;

    if (!name || !phone || !course || isNaN(age)) {
      result.innerHTML = `<span class="result-err">⚠ ${lang === "rn" ? "Yuzura ibisabwa vyose." : "Please fill in all fields."}</span>`;
      return;
    }

    btn.disabled = true;
    btn.classList.add("loading");
    if (txtEl) txtEl.textContent = "";

    try {
      const res = await fetch("http://localhost:3000/enroll", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name, age, phone, course, lang }),
      });

      const data = await res.json();
      if (data.success) {
        result.innerHTML = `<span class="result-ok">${t.successMsg(name, phone)}</span>`;
        form.reset();
      } else {
        result.innerHTML = `<span class="result-err">⚠ ${data.message || t.errorMsg}</span>`;
      }
    } catch (err) {
      console.error("Connection failed:", err);
      result.innerHTML = `<span class="result-err">Could not connect to server.</span>`;
    } finally {
      btn.disabled = false;
      btn.classList.remove("loading");
      if (txtEl) txtEl.innerHTML = t.fBtn;
    }
  });

